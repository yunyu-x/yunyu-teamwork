import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { EventEmitter } from 'node:events';

export const WIKI_CATEGORIES = Object.freeze({
  OVERVIEW: 'overview',
  ARCHITECTURE: 'architecture',
  PROTOCOL: 'protocol',
  OPERATIONS: 'operations',
  DECISION: 'decision',
  MODULE: 'module',
  CUSTOM: 'custom'
});

const VALID_WIKI_CATEGORIES = new Set(Object.values(WIKI_CATEGORIES));

const PAGE_ORDER = [
  'home',
  'architecture',
  'api-and-protocols',
  'workflows-and-ops',
  'decisions-and-pitfalls'
];

const RESERVED_WIKI_SLUGS = new Set([
  'readme',
  'con',
  'prn',
  'aux',
  'nul',
  'com1', 'com2', 'com3', 'com4', 'com5', 'com6', 'com7', 'com8', 'com9',
  'lpt1', 'lpt2', 'lpt3', 'lpt4', 'lpt5', 'lpt6', 'lpt7', 'lpt8', 'lpt9'
]);

export function sanitizeWikiSlug(rawSlug) {
  const slug = String(rawSlug || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9_-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80);
  if (!slug) throw new Error('Wiki 页面 slug 不能为空且仅支持字母、数字与连字符');
  if (RESERVED_WIKI_SLUGS.has(slug)) {
    throw new Error(`Wiki 页面 slug "${slug}" 为保留名称，请改用其他标识（如 "${slug}-doc"）`);
  }
  return slug;
}

function sha256Short(text) {
  return crypto.createHash('sha256').update(String(text || '')).digest('hex').slice(0, 12);
}

/**
 * Append-only, versioned Living Project Wiki persisted in `events.jsonl`.
 * Auto-synthesizes living architecture, module, protocol, workflow, and decision docs
 * from ProjectWorldModel + KnowledgeVault + ProjectAuditor, while preserving every human
 * and agent revision in an immutable audit trail.
 */
export class ProjectWiki extends EventEmitter {
  constructor({ swarmId, storage = null }) {
    super();
    this.swarmId = swarmId;
    this.storage = storage;
    this.pages = new Map(); // slug -> page object with revisions[]
  }

  replayFromStorage() {
    if (!this.storage) return;
    this.pages.clear();
    const events = this.storage.readEvents(this.swarmId);
    for (const ev of events) {
      if (ev.type === 'wiki_upsert' && ev.page?.slug) {
        this._applyPageEvent(ev.page);
      }
    }
  }

  _applyPageEvent(payload) {
    const slug = sanitizeWikiSlug(payload.slug);
    const existing = this.pages.get(slug);
    const revEntry = payload.revision || {
      version: payload.version || (existing ? existing.version + 1 : 1),
      updatedAt: payload.updatedAt || new Date().toISOString(),
      author: payload.author || 'system',
      summary: payload.summary || '更新页面',
      contentHash: sha256Short(payload.content)
    };

    const revisions = existing ? [...existing.revisions, revEntry] : [revEntry];
    const page = {
      slug,
      title: payload.title || existing?.title || slug,
      category: VALID_WIKI_CATEGORIES.has(payload.category)
        ? payload.category
        : existing?.category || WIKI_CATEGORIES.CUSTOM,
      content: String(payload.content ?? ''),
      author: payload.author || existing?.author || 'system',
      tags: Array.isArray(payload.tags) ? [...new Set(payload.tags)] : existing?.tags || [],
      autoGenerated: payload.autoGenerated ?? existing?.autoGenerated ?? false,
      version: revEntry.version,
      contentHash: revEntry.contentHash,
      createdAt: existing?.createdAt || revEntry.updatedAt,
      updatedAt: revEntry.updatedAt,
      revisions
    };
    this.pages.set(slug, page);
    return page;
  }

  upsertPage({
    slug,
    title,
    category = WIKI_CATEGORIES.CUSTOM,
    content = '',
    author = 'human',
    summary = '更新文档内容',
    tags = undefined,
    autoGenerated = false,
    skipIfUnchanged = false
  }) {
    const cleanSlug = sanitizeWikiSlug(slug);
    const cleanTitle = String(title || '').trim();
    if (!cleanTitle) throw new Error('Wiki 页面标题不能为空');

    const body = String(content || '').trim();
    const contentHash = sha256Short(body);
    const existing = this.pages.get(cleanSlug);

    if (skipIfUnchanged && existing && existing.contentHash === contentHash && existing.title === cleanTitle) {
      return structuredClone(existing);
    }

    const version = existing ? existing.version + 1 : 1;
    const now = new Date().toISOString();
    const normalizedTags =
      tags === undefined
        ? existing?.tags || []
        : [...new Set((Array.isArray(tags) ? tags : []).map((t) => String(t).trim().toLowerCase()).filter(Boolean))];
    const revision = {
      version,
      updatedAt: now,
      author: author || 'human',
      summary: String(summary || (version === 1 ? '首次创建页面' : '更新页面')).trim(),
      contentHash
    };

    const eventPayload = {
      slug: cleanSlug,
      title: cleanTitle,
      category: VALID_WIKI_CATEGORIES.has(category) ? category : existing?.category || WIKI_CATEGORIES.CUSTOM,
      content: body,
      author: author || 'human',
      tags: normalizedTags,
      autoGenerated: Boolean(autoGenerated),
      version,
      updatedAt: now,
      revision
    };

    const page = this._applyPageEvent(eventPayload);
    this.storage?.appendEvent(this.swarmId, { type: 'wiki_upsert', page: eventPayload });
    this.emit('wiki', { op: 'upsert', page: structuredClone(page) });
    return structuredClone(page);
  }

  getPage(slug) {
    try {
      const clean = sanitizeWikiSlug(slug);
      const page = this.pages.get(clean);
      return page ? structuredClone(page) : null;
    } catch {
      return null;
    }
  }

  listPages() {
    const all = [...this.pages.values()].map((p) => structuredClone(p));
    all.sort((a, b) => {
      const ia = PAGE_ORDER.indexOf(a.slug);
      const ib = PAGE_ORDER.indexOf(b.slug);
      if (ia !== -1 && ib !== -1) return ia - ib;
      if (ia !== -1) return -1;
      if (ib !== -1) return 1;
      if (a.slug.startsWith('module-') && !b.slug.startsWith('module-')) return -1;
      if (!a.slug.startsWith('module-') && b.slug.startsWith('module-')) return 1;
      return a.slug.localeCompare(b.slug);
    });
    return all;
  }

  search({ q = '', category = 'all', tag = '', limit = 30 } = {}) {
    let list = this.listPages();
    if (category && category !== 'all') {
      list = list.filter((p) => p.category === category);
    }
    if (tag) {
      const cleanTag = String(tag).trim().toLowerCase();
      list = list.filter((p) => (p.tags || []).includes(cleanTag));
    }
    const query = String(q || '').trim().toLowerCase();
    if (query) {
      const tokens = query.split(/\s+/).filter(Boolean);
      list = list.filter((p) => {
        const hay = [p.slug, p.title, p.content, p.author, (p.tags || []).join(' ')].join(' ').toLowerCase();
        return tokens.every((tok) => hay.includes(tok));
      });
    }
    return limit > 0 ? list.slice(0, limit) : list;
  }

  /**
   * Auto-generate living multi-page Wiki archives from a ProjectWorldModel snapshot
   * and optional runtime Swarm / KnowledgeVault / AuditReport context.
   */
  generateFromWorldModel(
    worldSnap,
    { projectName = null, swarm = null, knowledge = null, auditReport = null, author = 'world-model' } = {}
  ) {
    if (!worldSnap || !worldSnap.stats) {
      throw new Error('generateFromWorldModel 需要有效的世界模型快照');
    }

    const pkg = worldSnap.packageInfo || {};
    const name = projectName || pkg.name || path.basename(worldSnap.repoPath || 'project');
    const version = pkg.version ? `v${pkg.version}` : '';
    const stats = worldSnap.stats;

    const createdOrUpdated = [];

    // 1. home — 项目总览与世界模型快照
    const domainTableRows = (worldSnap.domains || [])
      .map(
        (d) =>
          `| \`${d.id}\` | ${d.label} | ${d.fileCount} | ${d.totalLoc} | ${d.exportsCount} | ${
            d.owners.length > 0 ? d.owners.map((o) => `\`@${o}\``).join(', ') : '—'
          } |`
      )
      .join('\n');

    const scriptsRows = Object.entries(pkg.scripts || {})
      .map(([k, v]) => `| \`npm run ${k}\` | \`${v}\` |`)
      .join('\n');

    const homeContent = [
      `# ${name} ${version} — 项目档案总览`,
      '',
      pkg.description ? `> ${pkg.description}` : '> 基于代码静态拓扑与实时协作状态自动生成的活文档（Living Project Wiki）。',
      '',
      '## 1. 世界模型核心指标',
      '',
      '| 指标 | 数值 | 说明 |',
      '| :--- | :--- | :--- |',
      `| 仓库健康度 | **${worldSnap.healthScore}/100** | 综合循环依赖、零外部依赖不变量、测试与所有权冲突评分 |`,
      `| 扫描文件总数 | ${stats.totalFiles}（源码 ${stats.codeFiles} / 测试 ${stats.testFiles} / 文档 ${stats.docFiles}） | 覆盖仓库主要代码与配置 |`,
      `| 总代码与文档行数 | ${stats.totalLoc} LOC | 总体积 ${(stats.totalBytes / 1024).toFixed(1)} KB |`,
      `| 模块导出符号 / 依赖边 | ${stats.totalExports} 导出 · ${stats.dependencyEdges} 依赖边 | 循环依赖：${stats.cyclesCount} 个 |`,
      `| 外部运行时依赖 | ${stats.runtimeDependencies} 个 | ${stats.runtimeDependencies === 0 ? '满足零外部运行时依赖铁律' : '存在外部运行时依赖，请核查'} |`,
      '',
      '## 2. 模块域分布全景',
      '',
      '| 域 ID | 职责描述 | 文件数 | 行数 (LOC) | 导出符号 | 所有权角色 |',
      '| :--- | :--- | ---: | ---: | ---: | :--- |',
      domainTableRows || '| — | 暂无模块 | 0 | 0 | 0 | — |',
      '',
      scriptsRows
        ? ['## 3. 常用工程脚本', '', '| 命令 | 实际执行 |', '| :--- | :--- |', scriptsRows].join('\n')
        : '',
      '',
      '> 本档案由云驭协同世界模型自动同步，完整修订时间线见页面元数据。'
    ]
      .filter(Boolean)
      .join('\n');

    createdOrUpdated.push(
      this.upsertPage({
        slug: 'home',
        title: `${name} 项目总览`,
        category: WIKI_CATEGORIES.OVERVIEW,
        content: homeContent,
        author,
        summary: '依据最新世界模型快照同步项目总览',
        tags: ['overview', 'world-model'],
        autoGenerated: true,
        skipIfUnchanged: true
      })
    );

    // 2. architecture — 系统架构与模块依赖拓扑
    const runtimeEdges = (worldSnap.domainEdges || []).filter((e) => e.kind === 'runtime');
    const safeMermaidId = (id) => `dom_${String(id || 'unknown').replace(/[^a-zA-Z0-9_]/g, '_')}`;
    const mermaidLines = [
      '```mermaid',
      'graph LR',
      ...runtimeEdges
        .slice(0, 20)
        .map((e) => `  ${safeMermaidId(e.from)}["${e.from}"] -->|${e.weight}| ${safeMermaidId(e.to)}["${e.to}"]`),
      runtimeEdges.length === 0 ? '  dom_core["core"] --> dom_server["server"]' : '',
      '```'
    ]
      .filter(Boolean)
      .join('\n');

    const hubsTable = (worldSnap.hubs || [])
      .map(
        (h) =>
          `| \`${h.path}\` | \`${h.domain}\` | ${h.fanIn} | ${h.fanOut} | ${h.loc} | ${
            h.owners.length > 0 ? h.owners.map((o) => `@${o}`).join(', ') : '—'
          } |`
      )
      .join('\n');

    const cyclesBlock =
      (worldSnap.cycles || []).length === 0
        ? '- 当前静态依赖图为严格有向无环图（DAG），**0 个循环依赖**。'
        : worldSnap.cycles.map((c, idx) => `- 环 #${idx + 1}: \`${c.join(' -> ')}\``).join('\n');

    const archContent = [
      '# 系统架构与模块依赖拓扑',
      '',
      '## 1. 域间运行时依赖关系',
      '',
      mermaidLines,
      '',
      '## 2. 高扇入核心枢纽（变更前必做爆炸半径评估）',
      '',
      '| 文件路径 | 所属域 | 被引用 (Fan-In) | 引用外部 (Fan-Out) | 行数 | 所有权 |',
      '| :--- | :--- | ---: | ---: | ---: | :--- |',
      hubsTable || '| — | — | 0 | 0 | 0 | — |',
      '',
      '## 3. 循环依赖与所有权边界检查',
      '',
      cyclesBlock,
      '',
      (worldSnap.collisions || []).length === 0
        ? '- 文件所有权边界检查：**0 处作者路径重叠冲突**。'
        : worldSnap.collisions.map((c) => `- ⚠️ ${c.message}`).join('\n')
    ].join('\n');

    createdOrUpdated.push(
      this.upsertPage({
        slug: 'architecture',
        title: '系统架构与依赖拓扑',
        category: WIKI_CATEGORIES.ARCHITECTURE,
        content: archContent,
        author,
        summary: '更新模块拓扑图、高扇入枢纽与循环依赖体检',
        tags: ['architecture', 'topology', 'dependencies'],
        autoGenerated: true,
        skipIfUnchanged: true
      })
    );

    // 3. api-and-protocols — 导出符号与协议接口清单
    const exportedFiles = (worldSnap.files || []).filter((f) => f.isCode && !f.isTest && f.exports.length > 0);
    const exportsRows = exportedFiles
      .slice(0, 45)
      .map((f) => `| \`${f.path}\` | \`${f.domain}\` | ${f.exports.slice(0, 8).map((e) => `\`${e}\``).join(', ')} |`)
      .join('\n');

    const builtins = (stats.builtinModules || []).map((b) => `\`${b}\``).join(', ') || '无';

    const apiContent = [
      '# 核心模块导出与协议接口清单',
      '',
      `## 1. Node.js 内置能力依赖`,
      '',
      `本项目使用的运行时内置模块：${builtins}`,
      '',
      '## 2. 源码导出符号索引',
      '',
      '| 模块路径 | 所属域 | 主要导出符号 |',
      '| :--- | :--- | :--- |',
      exportsRows || '| — | — | — |'
    ].join('\n');

    createdOrUpdated.push(
      this.upsertPage({
        slug: 'api-and-protocols',
        title: '模块导出与协议接口清单',
        category: WIKI_CATEGORIES.PROTOCOL,
        content: apiContent,
        author,
        summary: '索引源码模块导出符号与内置运行时依赖',
        tags: ['api', 'exports', 'protocols'],
        autoGenerated: true,
        skipIfUnchanged: true
      })
    );

    // 4. workflows-and-ops — 研发协同、测试矩阵与质量门禁
    const testFiles = (worldSnap.files || []).filter((f) => f.isTest);
    const testList =
      testFiles.length > 0
        ? testFiles.map((f) => `- \`${f.path}\` (${f.loc} 行 · 覆盖依赖 ${f.imports.length} 个源码模块)`).join('\n')
        : '- 尚未检测到自动化测试文件，建议尽快补充单元与集成测试。';

    const auditSummary = auditReport
      ? [
          '## 3. 最近一次全仓自动审计快照',
          '',
          `- 审计评分：**${auditReport.score}/100**（${auditReport.passed ? '通过' : '存在阻断项'}）`,
          `- 发现数：P0=${auditReport.summary.p0} · P1=${auditReport.summary.p1} · P2=${auditReport.summary.p2}`,
          ...(auditReport.findings || [])
            .slice(0, 8)
            .map((f) => `- **[${f.severity}/${f.category}]** ${f.file ? `\`${f.file}\` ` : ''}${f.message}`)
        ].join('\n')
      : '';

    const opsContent = [
      '# 工程规范、测试矩阵与质量门禁',
      '',
      '## 1. 自动化测试清单',
      '',
      testList,
      '',
      '## 2. 协作交付标准流程',
      '',
      '1. 修改高扇入核心文件前，先运行「变更爆炸半径模拟器」识别受影响的下游域、测试集与协作成员。',
      '2. 并发作者通过独立 Git Worktree (`workspace: "share"`) 隔离改动，合并前执行 `OwnershipGuard` 越权审计。',
      '3. 验证者 / 复核者 / 情报研究员严格保持对 `src/` 与 `web/` 只读，发现缺陷在留言板 `@author` 或开具 Qoder Issue。',
      '4. 发布前必须依次通过语法直检、单测/集成测试、无头 Chrome UI QA 与全仓安全审计门禁。',
      '',
      auditSummary
    ]
      .filter(Boolean)
      .join('\n');

    createdOrUpdated.push(
      this.upsertPage({
        slug: 'workflows-and-ops',
        title: '工程规范与质量门禁',
        category: WIKI_CATEGORIES.OPERATIONS,
        content: opsContent,
        author,
        summary: '同步测试覆盖清单、交付规程与自动审计摘要',
        tags: ['workflow', 'qa', 'operations'],
        autoGenerated: true,
        skipIfUnchanged: true
      })
    );

    // 5. decisions-and-pitfalls — 架构决策、知识沉淀与避坑档案
    const kbEntries = knowledge?.listEntries ? knowledge.listEntries() : [];
    const kbSection =
      kbEntries.length > 0
        ? kbEntries
            .slice(0, 12)
            .map(
              (e) =>
                `### ${e.title}\n- 分类：\`${e.category}\` · 作者：\`@${e.author}\` · 时间：\`${e.createdAt}\`\n- 摘要：${
                  e.summary || '—'
                }\n`
            )
            .join('\n')
        : '- 当前蜂群共享知识库暂无条目，可通过 `@researcher` 采集竞品/文档情报或由架构师写入 ADR 沉淀。';

    const runtimeSection = worldSnap.runtime
      ? [
          '## 2. 当前蜂群运行态快照',
          '',
          `- 成员总数：${worldSnap.runtime.memberCount}（工作中：${worldSnap.runtime.activeMembers.length}）`,
          `- Issue 进度：总计 ${worldSnap.runtime.totalTasks} · 待完成 ${worldSnap.runtime.openTasks} · 就绪可认领 ${worldSnap.runtime.readyTasks}`,
          `- 知识库条目：${worldSnap.runtime.knowledgeCount} 条`
        ].join('\n')
      : '';

    const decisionContent = [
      '# 架构决策、情报沉淀与避坑档案',
      '',
      '## 1. 共享知识库精选（ADR / 调研报告 / 避坑指南）',
      '',
      kbSection,
      '',
      runtimeSection
    ]
      .filter(Boolean)
      .join('\n');

    createdOrUpdated.push(
      this.upsertPage({
        slug: 'decisions-and-pitfalls',
        title: '架构决策与避坑档案',
        category: WIKI_CATEGORIES.DECISION,
        content: decisionContent,
        author,
        summary: '同步共享知识库沉淀与蜂群运行态快照',
        tags: ['adr', 'knowledge', 'pitfalls'],
        autoGenerated: true,
        skipIfUnchanged: true
      })
    );

    // 6. Per-domain module deep-dive pages for primary source domains
    const codeDomains = (worldSnap.domains || [])
      .filter((d) => d.codeFileCount > 0 && !['tests', 'docs', 'root', 'scripts', 'examples'].includes(d.id))
      .slice(0, 8);

    for (const dom of codeDomains) {
      const domFiles = (worldSnap.files || []).filter((f) => f.domain === dom.id && f.isCode);
      const rows = domFiles
        .map(
          (f) =>
            `| \`${f.path}\` | ${f.loc} | ${f.fanIn} | ${f.fanOut} | ${
              f.exports.slice(0, 6).map((e) => `\`${e}\``).join(', ') || '—'
            } |`
        )
        .join('\n');

      const outDeps = (worldSnap.domainEdges || [])
        .filter((e) => e.from === dom.id && e.kind === 'runtime')
        .map((e) => `\`${e.to}\` (${e.weight}条边)`);
      const inDeps = (worldSnap.domainEdges || [])
        .filter((e) => e.to === dom.id && e.kind === 'runtime')
        .map((e) => `\`${e.from}\` (${e.weight}条边)`);

      const modContent = [
        `# 模块域详解：${dom.label}`,
        '',
        `- 文件数：${dom.codeFileCount} · 总行数：${dom.totalLoc} LOC · 导出符号：${dom.exportsCount}`,
        `- 依赖下游域：${outDeps.length > 0 ? outDeps.join(', ') : '无外部域依赖（底层独立域）'}`,
        `- 被上游域调用：${inDeps.length > 0 ? inDeps.join(', ') : '顶层入口域'}`,
        '',
        '## 文件清单与符号契约',
        '',
        '| 文件 | 行数 | Fan-In | Fan-Out | 导出符号 |',
        '| :--- | ---: | ---: | ---: | :--- |',
        rows
      ].join('\n');

      createdOrUpdated.push(
        this.upsertPage({
          slug: `module-${dom.id}`,
          title: `模块域：${dom.label}`,
          category: WIKI_CATEGORIES.MODULE,
          content: modContent,
          author,
          summary: `自动生成 ${dom.id} 模块域档案`,
          tags: ['module', dom.id],
          autoGenerated: true,
          skipIfUnchanged: true
        })
      );
    }

    return createdOrUpdated;
  }

  /**
   * Export all wiki pages as standalone Markdown files + README.md index.
   */
  exportToDir(outDir) {
    const absOut = path.resolve(outDir);
    fs.mkdirSync(absOut, { recursive: true });
    const pages = this.listPages();
    const writtenFiles = [];

    for (const page of pages) {
      const safeSlug = sanitizeWikiSlug(page.slug);
      const filePath = path.join(absOut, `${safeSlug}.md`);
      const header = [
        `<!-- yunyu-wiki slug=${safeSlug} version=${page.version} category=${page.category} updatedAt=${page.updatedAt} -->`,
        ''
      ].join('\n');
      fs.writeFileSync(filePath, `${header}${page.content}\n`, 'utf8');
      writtenFiles.push(filePath);
    }

    const indexLines = [
      '# 项目 Wiki 档案索引（Living Project Wiki）',
      '',
      '> 本目录由云驭协同（Yunyu Teamwork）世界模型与活文档引擎自动导出，包含架构拓扑、模块契约、工程门禁与决策档案。',
      '',
      '| 页面 | 分类 | 版本 | 最近修订 | 作者 |',
      '| :--- | :--- | ---: | :--- | :--- |',
      ...pages.map(
        (p) =>
          `| [${p.title}](./${p.slug}.md) | \`${p.category}\` | v${p.version} | \`${p.updatedAt.slice(0, 19).replace('T', ' ')}\` | \`@${p.author}\` |`
      ),
      ''
    ].join('\n');

    const indexPath = path.join(absOut, 'README.md');
    fs.writeFileSync(indexPath, indexLines, 'utf8');
    writtenFiles.push(indexPath);

    return {
      outDir: absOut,
      pageCount: pages.length,
      files: writtenFiles
    };
  }
}
